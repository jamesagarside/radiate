"""The API contract with the Home Assistant integration (the radiate-ha repository).

`fixtures/ha` holds the `house` and `state` responses that radiate-ha's tests run against.
They were generated by `scripts/ha_fixtures.py`. A server change that drops or renames a field
the integration was tested with fails here, before it breaks Home Assistant users.
Adding fields is fine. Regenerate the fixtures and copy them to radiate-ha when it needs them.
"""

import json
from pathlib import Path

import pytest

from scripts.ha_fixtures import generate

FIXTURES = Path(__file__).parent / "fixtures" / "ha"


def key_paths(value, prefix: str = "", wildcard: frozenset[str] = frozenset()) -> set[str]:
    """Every key path in a JSON value. List items share one path, `name[]`, and keys in
    `wildcard` (room IDs, which key some maps) become `*`, since which rooms appear depends
    on how the run went."""
    paths: set[str] = set()
    if isinstance(value, dict):
        for k, v in value.items():
            k = "*" if k in wildcard else k
            p = f"{prefix}.{k}" if prefix else k
            paths.add(p)
            paths |= key_paths(v, p, wildcard)
    elif isinstance(value, list):
        for item in value:
            paths |= key_paths(item, f"{prefix}[]", wildcard)
    return paths


def test_key_paths():
    assert key_paths({"a": [{"b": 1}, {"c": {"d": None}}]}) == {"a", "a[].b", "a[].c", "a[].c.d"}
    assert key_paths({"m": {"lounge": 1}}, wildcard=frozenset({"lounge"})) == {"m", "m.*"}


@pytest.mark.parametrize("name", ["house", "state"])
async def test_server_returns_every_field_the_integration_uses(name):
    house, state = await generate()
    fresh = {"house": house, "state": state}[name]
    saved = json.loads((FIXTURES / f"{name}.json").read_text())
    rooms = frozenset(r["id"] for r in house["rooms"])
    missing = sorted(key_paths(saved, wildcard=rooms) - key_paths(fresh, wildcard=rooms))
    assert not missing, (
        f"/api/v1/{name} no longer returns {missing}. The Home Assistant integration "
        "(radiate-ha) reads these fields: keep them, or change radiate-ha first and then "
        "regenerate tests/server/fixtures/ha with scripts/ha_fixtures.py."
    )
